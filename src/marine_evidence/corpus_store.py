"""Local mutable document collection layered on the immutable benchmark PDF corpus.

The original 8 papers/chunks are never modified. Uploads live under data/app/;
only the registry refers to active uploads. All stored paths are generated by us,
not derived from a client-provided filename. The BM25 index is rebuilt on upload
and delete; suitable for a small single-process localhost application.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import tempfile
import threading
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

import fitz

from .bm25 import BM25Index, read_chunks
from .chunk_word_safe import page_to_chunks
from .ingest import normalize_text

MAX_UPLOAD_BYTES = 25 * 1024 * 1024
MAX_PAGES = 100
MAX_TEXT_CHARS = 2_000_000
ID_PATTERN = re.compile(r"^[A-Z][A-Z0-9_-]{1,40}$")


class DocumentError(ValueError):
    """An upload or document operation was rejected."""


def _atomic_bytes(path: Path, payload: bytes) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp: Path | None = None
    try:
        with tempfile.NamedTemporaryFile('wb', dir=path.parent, delete=False, suffix='.tmp') as fh:
            tmp = Path(fh.name)
            fh.write(payload)
            fh.flush()
            os.fsync(fh.fileno())
        os.replace(tmp, path)
    finally:
        if tmp is not None:
            tmp.unlink(missing_ok=True)


def _atomic_json(path: Path, data: Any) -> None:
    _atomic_bytes(path, (json.dumps(data, ensure_ascii=False, indent=2) + '\n').encode('utf-8'))


def _safe_filename(name: str) -> str:
    name = re.split(r'[/\\]', name or '')[-1]
    name = ''.join(c for c in name if c.isprintable() and c not in '<>:"|?*')
    name = name.strip(' .')[:180]
    if not name or not name.lower().endswith('.pdf'):
        raise DocumentError('Only .pdf documents are supported')
    return name


def extract_uploaded_pdf(data: bytes, original_filename: str) -> tuple[dict[str, Any], list[dict[str, Any]]]:
    """Validate/upload one PDF using the existing extraction + chunking functions.

    No filename is used as a disk path. Uploaded PDF text is treated as untrusted
    document data, never instructions. Scanned-only files require OCR (unsupported).
    """
    filename = _safe_filename(original_filename)
    if not data:
        raise DocumentError('PDF is empty')
    if len(data) > MAX_UPLOAD_BYTES:
        raise DocumentError('PDF exceeds the 25 MiB upload limit')
    if not data.startswith(b'%PDF-'):
        raise DocumentError('File does not have a valid PDF header')

    digest = hashlib.sha256(data).hexdigest()
    source_id = 'U' + digest[:16].upper()
    pages = []
    text_chars = 0
    try:
        with fitz.open(stream=data, filetype='pdf') as doc:
            if doc.needs_pass:
                raise DocumentError('Password-protected PDFs are not supported')
            if not 1 <= len(doc) <= MAX_PAGES:
                raise DocumentError(f'PDF must contain 1–{MAX_PAGES} pages')
            metadata_title = (doc.metadata or {}).get('title') or ''
            clean_title = ''.join(c for c in metadata_title if c.isprintable()).strip()
            title = clean_title[:200] if len(clean_title) >= 5 else Path(filename).stem
            for page_idx, page in enumerate(doc, start=1):
                text = normalize_text(page.get_text('text', sort=False))
                text_chars += len(text)
                if text_chars > MAX_TEXT_CHARS:
                    raise DocumentError('PDF has too much extracted text for this MVP')
                pages.append({
                    'page_id': f'{source_id}:p{page_idx:04d}',
                    'source_id': source_id,
                    'filename': filename,
                    'title': title,
                    'doi': '',
                    'pdf_page': page_idx,
                    'text': text,
                    'char_count': len(text),
                })
    except DocumentError:
        raise
    except (RuntimeError, ValueError, TypeError) as exc:
        raise DocumentError('Invalid, damaged, or unreadable PDF') from exc

    if text_chars < 100:
        raise DocumentError('PDF contains too little selectable text; OCR is not supported yet')
    chunks = []
    for page in pages:
        if page['text'].strip():
            try:
                chunks.extend(page_to_chunks(page, max_chars=2000, overlap_chars=300))
            except ValueError as exc:
                raise DocumentError(f'PDF cannot be chunked safely: {exc}') from exc
    if not chunks:
        raise DocumentError('No searchable text extracted from PDF')
    record = {
        'source_id': source_id,
        'filename': filename,
        'title': title,
        'doi': '',
        'sha256': digest,
        'pages': len(pages),
        'chunks': len(chunks),
        'uploaded': True,
        'added_at': datetime.now(timezone.utc).isoformat(timespec='seconds'),
    }
    return record, chunks


class CorpusStore:
    def __init__(self, *, base_chunks_path: Path, base_papers_dir: Path, uploads_dir: Path,
                 base_manifest_path: Path | None = None):
        self._lock = threading.RLock()
        self.base_papers_dir = Path(base_papers_dir)
        self.uploads_dir = Path(uploads_dir)
        self.registry_path = self.uploads_dir / 'registry.json'
        self.pdf_dir = self.uploads_dir / 'pdfs'
        self.chunks_dir = self.uploads_dir / 'chunks'
        self.base_chunks = read_chunks(Path(base_chunks_path))
        self.base_documents: dict[str, dict[str, Any]] = {}
        for chunk in self.base_chunks:
            sid = chunk['source_id']
            if not ID_PATTERN.fullmatch(sid):
                raise DocumentError(f'Bad base source ID: {sid!r}')
            if sid not in self.base_documents:
                self.base_documents[sid] = {
                    'source_id': sid, 'filename': chunk['filename'],
                    'title': chunk['title'], 'doi': chunk.get('doi', ''),
                    'pages': 0, 'chunks': 0, 'uploaded': False, 'sha256': '',
                }
            item = self.base_documents[sid]
            item['chunks'] += 1
            item['pages'] = max(item['pages'], chunk['pdf_page'])
        if base_manifest_path is not None and Path(base_manifest_path).is_file():
            manifests = json.loads(Path(base_manifest_path).read_text(encoding='utf-8'))
            for p in manifests:
                rec = self.base_documents.get(p.get('id', ''))
                if rec:
                    rec['pages'] = p.get('pdf_page_count', rec['pages'])
                    rec['sha256'] = p.get('sha256', '')
        self.uploads_dir.mkdir(parents=True, exist_ok=True)
        if self.registry_path.exists():
            registry = json.loads(self.registry_path.read_text(encoding='utf-8'))
            if not isinstance(registry, list):
                raise DocumentError('Upload registry is not a list')
        else:
            registry = []
        self.uploaded_documents: dict[str, dict[str, Any]] = {}
        self.uploaded_chunks: dict[str, list[dict[str, Any]]] = {}
        for rec in registry:
            sid = rec.get('source_id', '')
            if (not isinstance(sid, str) or not ID_PATTERN.fullmatch(sid)
                    or not sid.startswith('U') or sid in self.base_documents
                    or sid in self.uploaded_documents):
                raise DocumentError('Corrupted or duplicate uploaded source ID')
            file_path = self.chunks_dir / (sid + '.jsonl')
            pdf_path = self.pdf_dir / (sid + '.pdf')
            if not pdf_path.is_file():
                raise DocumentError(f'Missing uploaded PDF for {sid}')
            self.uploaded_chunks[sid] = read_chunks(file_path)
            self.uploaded_documents[sid] = rec
        self.index = self._build_index()

    @classmethod
    def from_project(cls, root: Path) -> 'CorpusStore':
        root = Path(root)
        return cls(
            base_chunks_path=root / 'data/chunks/word_safe/chunks.jsonl',
            base_papers_dir=root / 'papers',
            uploads_dir=root / 'data/app',
            base_manifest_path=root / 'evaluation/papers_manifest.json',
        )

    def _build_index(self, extra: list[dict[str, Any]] | None = None,
                     skip: str | None = None) -> BM25Index:
        chunks = list(self.base_chunks)
        for sid, rows in sorted(self.uploaded_chunks.items()):
            if sid != skip:
                chunks.extend(rows)
        if extra is not None:
            chunks.extend(extra)
        return BM25Index(chunks)

    @property
    def chunk_count(self) -> int:
        with self._lock:
            return self.index.n_docs

    def list_documents(self) -> list[dict[str, Any]]:
        with self._lock:
            return [dict(d) for d in (list(self.base_documents.values()) +
                                     list(self.uploaded_documents.values()))]

    def upload_pdf(self, data: bytes, filename: str) -> tuple[dict[str, Any], bool]:
        record, rows = extract_uploaded_pdf(data, filename)
        sid = record['source_id']
        with self._lock:
            for old in self.base_documents.values():
                if old.get('sha256') == record['sha256']:
                    return dict(old), True
            if sid in self.uploaded_documents:
                old = self.uploaded_documents[sid]
                if old['sha256'] != record['sha256']:
                    raise DocumentError('Source identifier collision')
                return dict(old), True
            new_index = self._build_index(extra=rows)
            pdf_path = self.pdf_dir / (sid + '.pdf')
            chunks_path = self.chunks_dir / (sid + '.jsonl')
            payload = ''.join(json.dumps(c, ensure_ascii=False) + '\n' for c in rows).encode('utf-8')
            try:
                _atomic_bytes(pdf_path, data)
                _atomic_bytes(chunks_path, payload)
                new_registry = list(self.uploaded_documents.values()) + [record]
                _atomic_json(self.registry_path, new_registry)
            except Exception:
                pdf_path.unlink(missing_ok=True)
                chunks_path.unlink(missing_ok=True)
                raise
            self.uploaded_documents[sid] = record
            self.uploaded_chunks[sid] = rows
            self.index = new_index
            return dict(record), False

    def delete_upload(self, sid: str) -> bool:
        with self._lock:
            if sid in self.base_documents:
                raise DocumentError('Original benchmark papers cannot be deleted via API')
            if sid not in self.uploaded_documents:
                return False
            new_index = self._build_index(skip=sid)
            remaining = [rec for k, rec in self.uploaded_documents.items() if k != sid]
            _atomic_json(self.registry_path, remaining)
            self.uploaded_documents.pop(sid)
            self.uploaded_chunks.pop(sid)
            self.index = new_index
            (self.pdf_dir / (sid + '.pdf')).unlink(missing_ok=True)
            (self.chunks_dir / (sid + '.jsonl')).unlink(missing_ok=True)
            return True

    def pdf_path(self, sid: str) -> tuple[Path, str] | None:
        if not isinstance(sid, str) or not ID_PATTERN.fullmatch(sid):
            return None
        with self._lock:
            if sid in self.uploaded_documents:
                return self.pdf_dir / (sid + '.pdf'), self.uploaded_documents[sid]['filename']
            if sid in self.base_documents:
                filename = self.base_documents[sid]['filename']
                if '/' in filename or '\\' in filename:
                    return None
                return self.base_papers_dir / filename, filename
        return None

    def search(self, question: str, *, top_k: int = 5, distinct_pages: bool = False) -> list[dict[str, Any]]:
        with self._lock:
            index = self.index
        return index.search(question, top_k=top_k, distinct_pages=distinct_pages)

    def snapshot_index(self) -> BM25Index:
        with self._lock:
            return self.index
